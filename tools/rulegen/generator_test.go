func TestNoOutputWrittenOnValidationFailure(t *testing.T) {
	dir := t.TempDir()
	outPath := filepath.Join(dir, "zz_generated_rules.go")
	fixturesPath := filepath.Join(dir, "zz_generated_fixtures_test.go")

	if err := run("testdata/duplicate/specs", outPath, fixturesPath); err == nil {
		t.Fatal("run() error = nil, want error")
	}
	if _, err := os.Stat(outPath); !os.IsNotExist(err) {
		t.Errorf("expected no rules file to be written on failure, stat error = %v", err)
	}
	if _, err := os.Stat(fixturesPath); !os.IsNotExist(err) {
		t.Errorf("expected no fixtures file to be written on failure, stat error = %v", err)
	}
}

func TestDuplicateTriggerLiteralsAcrossRulesAreAllowed(t *testing.T) {
	// testdata/valid/specs deliberately has two rules ("zzz-last" in
	// a.json and "mmm-middle" in b.json) sharing the trigger literal
	// "zzz_". This must not be a validation error: the runtime automaton
	// dedupes triggers, and dispatch fans a hit out to every rule that
	// registered it.
	if _, _, err := runGen(t, "testdata/valid/specs"); err != nil {
		t.Fatalf("run() error = %v, want nil (duplicate trigger literals across rules must be allowed)", err)
	}
}
